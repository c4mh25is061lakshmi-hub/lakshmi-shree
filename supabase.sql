create table if not exists public.students (
  id bigint generated by default as identity primary key,
  roll_no text not null,
  name text not null check (char_length(btrim(name)) between 1 and 100),
  branch text not null check (branch in ('CS', 'EC', 'ME', 'IS', 'AI')),
  gpa numeric not null check (gpa between 0 and 10),
  email text not null check (email = btrim(email)),
  gender text not null check (gender in ('Female', 'Male', 'Other')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint students_roll_no_format check (
    char_length(roll_no) between 3 and 20
    and roll_no ~ '^[A-Za-z0-9]+(-[A-Za-z0-9]+)*$'
  ),
  constraint students_roll_no_unique unique (roll_no)
);

create unique index if not exists students_roll_no_normalized_unique
  on public.students (upper(replace(roll_no, '-', '')));

create or replace function public.set_student_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_student_updated_at on public.students;
create trigger set_student_updated_at
before update on public.students
for each row
execute function public.set_student_updated_at();

alter table public.students enable row level security;

drop policy if exists "Public can read students" on public.students;
create policy "Public can read students"
  on public.students for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can add students" on public.students;
create policy "Public can add students"
  on public.students for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Public can update students" on public.students;
create policy "Public can update students"
  on public.students for update
  to anon, authenticated
  using (true)
  with check (true);

drop policy if exists "Public can delete students" on public.students;
create policy "Public can delete students"
  on public.students for delete
  to anon, authenticated
  using (true);

grant select, insert, update, delete on public.students to anon, authenticated;
grant usage, select on sequence public.students_id_seq to anon, authenticated;
grant usage on schema public to anon, authenticated;

